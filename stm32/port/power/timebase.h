/*
 * Таймбейз HAL на LPTIM1 вместо SysTick.
 *
 * HAL_GetTick()/HAL_Delay() читают свободно идущий счётчик LPTIM1 (тактирование
 * LSI 32 кГц, предделитель /32 -> 1 кГц, 1 тик = 1 мс), а не переменную uwTick,
 * которую раз в миллисекунду увеличивало прерывание SysTick. Прерываний у
 * таймбейза нет, поэтому МК не просыпается 1000 раз в секунду, а счётчик идёт и
 * в Stop 2: после сна время HAL не нужно "добирать".
 *
 * SysTick не используется вообще: HAL_InitTick() переопределена здесь (CubeMX
 * оставляет Timebase Source = SysTick, см. docs/hardware.md), SysTick_Handler из
 * stm32u5xx_it.c никогда не вызывается.
 *
 * Тот же LPTIM1 даёт и будильник (канал сравнения CC1): им будят МК из Sleep
 * (stm32_app.c) и Stop 2 (stop_mode.c).
 *
 * Точность хода - точность LSI (единицы процентов, без калибровки). Время HAL
 * нужно для таймаутов, debounce и периодических задач; время по спутникам берётся
 * из решения GNSS.
 */
#ifndef PURRGO_TIMEBASE_H
#define PURRGO_TIMEBASE_H

#include <stdbool.h>
#include <stdint.h>

/*
 * Счётчик LPTIM1 16-битный: на 1 кГц он переполняется каждые 65,536 с. Старшие
 * разряды HAL_GetTick() набираются при самом чтении, без прерывания переполнения,
 * поэтому между двумя вызовами HAL_GetTick() должно пройти меньше этого времени
 * (с запасом). Главный цикл вызывает его на каждом проходе, а сон ограничен
 * PURRGO_SLEEP_MAX_MS / PURRGO_STOP2_MAX_MS (stm32_app.c, там же проверка).
 */
#define PURRGO_TIMEBASE_MAX_GAP_MS 60000U

/* true - LPTIM1 запущен и HAL_GetTick() идёт. */
bool purrgo_timebase_ready(void);

/*
 * Поставить будильник на ms миллисекунд вперёд (1..32767) и разрешить линию NVIC
 * LPTIM1. Вызывать при взведённом PRIMASK (__disable_irq()): прерывание не
 * выполняется, но будит из WFI / Stop 2. Обработчик LPTIM1 только снимает флаг.
 *
 * false - будильник не поставлен (таймбейз не запущен, сбой синхронизации или
 * срок уже прошёл, пока записывался регистр сравнения): спать нельзя, нужен
 * следующий проход цикла. После WFI вызвать purrgo_timebase_wake_disarm().
 */
bool purrgo_timebase_wake_arm(uint32_t ms);

/* Снять будильник: выключить линию NVIC, сбросить флаг и ожидающее прерывание. */
void purrgo_timebase_wake_disarm(void);

#endif /* PURRGO_TIMEBASE_H */
