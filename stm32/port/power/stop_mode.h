/*
 * Stop 2 для режима чтения (STM32U585).
 *
 * В читалке экран не зависит от времени, а GNSS и LPUART выключены: от главного
 * цикла нужно только реагировать на кнопки. Пока E-Ink статичен, МК уходит в
 * Stop 2 (единицы мкА вместо ~8 мА в Sleep на 80 МГц).
 *
 * Время HAL (HAL_GetTick) - свободно идущий счётчик LPTIM1 на LSI (timebase.h):
 * он работает и в Stop 2, поэтому таймауты ядра (сохранение позиции, опрос
 * батареи, PVD) остаются корректными без какого-либо добора времени после сна.
 * Точность хода - точность LSI (единицы процентов): для таймаутов в десятки
 * секунд достаточно.
 *
 * Пробуждение: кнопки K1..K4 (EXTI, спад) или будильник LPTIM1.
 */
#ifndef PURRGO_STOP_MODE_H
#define PURRGO_STOP_MODE_H

#include <stdbool.h>
#include <stdint.h>

/*
 * Подготовить Stop 2 (LPTIM1 уже запущен как таймбейз HAL, см. timebase.h).
 * Вызывается один раз при старте. false - таймбейз не идёт, Stop 2 недоступен,
 * purrgo_stop2_enter() вернёт false.
 */
bool purrgo_stop2_init(void);

/*
 * Войти в Stop 2 не более чем на max_ms. Возвращает после пробуждения (кнопка
 * или таймаут) с восстановленной тактовой частотой. false - в Stop не входили (кнопка уже нажата или Stop 2
 * недоступен): вызывающий должен выполнить обычный WFI.
 */
bool purrgo_stop2_enter(uint32_t max_ms);

/*
 * POWER OFF через Stop 2 вместо Standby (замеры: Standby 5,17 мА против 2,75 мА
 * в Stop 2 при той же плате). Будит только K1 (спад), после пробуждения -
 * NVIC_SystemReset(): запуск как после Standby. При успехе не возвращается.
 * false - Stop 2 недоступен (purrgo_stop2_init() не вызывался или завершился
 * ошибкой): вызывающий должен перейти в Standby.
 */
bool purrgo_stop2_power_off(void);

#endif /* PURRGO_STOP_MODE_H */
