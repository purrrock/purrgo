#ifndef EINK_TEST_H
#define EINK_TEST_H

#include <stdint.h>

/*
 * Минимальный аппаратный тест Waveshare 2.7" E-Ink V2 в 1-bit режиме
 * библиотеки epd4g (напрямую, без слоя display_eink):
 *   1. bw_init, bw_full с чередующимися чёрно-белыми полосами;
 *   2. deep sleep.
 *
 * Блокирует до завершения полного обновления.
 */
void EinkTest_Run(void);

/*
 * Тест 4-gray через ТОТ ЖЕ путь, что использует приложение:
 * display_eink_init() -> запрос полного обновления в режиме 4 gray (2 бита на пиксель).
 *
 * EinkTest_Run() рисует только константные полосы (байты 0x00/0xFF) в
 * 1-bit режиме: такие данные не содержат переходов на линии MOSI и не
 * проверяют ни целостность SPI, ни загрузку LUT 4-gray. Этот тест
 * содержит:
 *   - 4 горизонтальные полосы (чёрный, тёмно-серый, светло-серый, белый);
 *   - вертикальные полосы шириной 1 пиксель (максимум переходов в данных);
 *   - шахматку 2x2;
 *   - градиент 4 уровней по горизонтали.
 *
 * Если этот тест даёт мусор, причина в 4-gray/SPI/питании, а не в
 * содержимом карты. Если картинка корректна, причину надо искать в
 * приложении (порядок инициализации, питание под нагрузкой и т.д.).
 */
void EinkTest_Run4Gray(void);

/*
 * Заполняет 2-bpp буфер PurrGO (176x264, MSB-first, 4 пикселя в байте)
 * тестовым рисунком. Вынесено отдельно, чтобы рисунок можно было
 * проверить на хосте.
 */
void EinkTest_FillPattern4Gray(uint8_t *fb2bpp, int width, int height);

/*
 * Тест частичного обновления через слой display_eink.
 *
 * 1. Режим 1 bit: рамка полным обновлением, затем 4 раза чёрный квадрат
 *    24x24 в новом месте, обновляется ТОЛЬКО окно квадрата.
 * 2. Режим 4 gray: полное обновление (смена режима), затем 4 квадрата
 *    разных оттенков серого; перерисовываются только изменившиеся пиксели.
 *
 * Экран не должен мигать при частичных обновлениях; квадраты остаются на
 * месте. В конце панель засыпает.
 */
void EinkTest_RunPartial(void);

#endif /* EINK_TEST_H */
