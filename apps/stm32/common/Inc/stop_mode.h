/*
 * Stop 2 для режима чтения (STM32U585).
 *
 * В читалке экран не зависит от времени, а GNSS и LPUART выключены: от главного
 * цикла нужно только реагировать на кнопки. Пока E-Ink статичен, МК уходит в
 * Stop 2 (единицы мкА вместо ~8 мА в Sleep на 80 МГц).
 *
 * SysTick в Stop 2 останавливается, поэтому время HAL (HAL_GetTick) после
 * пробуждения добирается по LPTIM1 на LSI: таймауты ядра (сохранение позиции,
 * опрос батареи, PVD) остаются корректными. Точность хода в Stop - точность LSI
 * (единицы процентов): для таймаутов в десятки секунд достаточно.
 *
 * Пробуждение: кнопки K1..K4 (EXTI, спад) или таймаут LPTIM1.
 */
#ifndef PURRGO_STOP_MODE_H
#define PURRGO_STOP_MODE_H

#include <stdbool.h>
#include <stdint.h>

/*
 * Включить LSI и LPTIM1 (свободный счётчик 250 Гц). Вызывается один раз при
 * старте. false - Stop 2 недоступен, purrgo_stop2_enter() вернёт false.
 */
bool purrgo_stop2_init(void);

/*
 * Войти в Stop 2 не более чем на max_ms. Возвращает после пробуждения (кнопка
 * или таймаут) с восстановленной тактовой частотой и скорректированным
 * HAL_GetTick(). false - в Stop не входили (кнопка уже нажата или Stop 2
 * недоступен): вызывающий должен выполнить обычный WFI.
 */
bool purrgo_stop2_enter(uint32_t max_ms);

#endif /* PURRGO_STOP_MODE_H */
