#ifndef DISPLAY_EINK_H
#define DISPLAY_EINK_H

#include <stdbool.h>
#include <stdint.h>

#include "purrgo/display_hal.h"

/*
 * Backend E-Ink Waveshare 2.7" V2 (176 x 264) на библиотеке epd4g
 * (third_party/eink_part_refresh/epd4g).
 *
 * Внутренний framebuffer PurrGO всегда 2-битный (11616 байт):
 *   0 = Black, 1 = Dark Gray, 2 = Light Gray, 3 = White.
 * Формат совпадает с буфером epd4g (176 x 264, 44 байта на строку).
 *
 * Режимы (display_mode_t, выбирает ядро по экрану):
 *   DISPLAY_MODE_GRAY4 - 4 gray; частичное обновление: перерисовываются
 *                        только пиксели, отличающиеся от предыдущего кадра
 *                        (буфер prev на 11616 байт);
 *   DISPLAY_MODE_MONO  - 1 бит, быстрое частичное обновление окна.
 *
 * Все обновления неблокирующие: request_* только запоминают запрос, а
 * display_eink_poll() (раз за проход главного цикла) продвигает автомат
 * библиотеки. Одновременно идёт одно обновление; запросы, пришедшие за это
 * время, сливаются (последний кадр + объединение областей).
 */

/*
 * Настроить SPI1 для панели и запомнить framebuffer. SPI1 и GPIO уже
 * инициализированы CubeMX. Панель при этом не трогается: инициализация
 * (reset + регистры) выполняется при первом обновлении.
 * framebuffer == NULL допустим только для аппаратных тестов, которые
 * работают с библиотекой напрямую.
 */
void display_eink_init(const uint8_t *framebuffer);

/* Режим вывода. Смена режима делает следующее обновление полным. */
void display_eink_set_mode(display_mode_t mode);

/* Запросить полное обновление (мигает весь экран). */
void display_eink_request_full(void);

/*
 * Запросить обновление области (пиксели, границы включительно, уже
 * обрезанные до экрана). GRAY4 игнорирует границы (сравнивается весь кадр),
 * MONO обновляет окно, расширенное по X до 8 пикселей.
 * Полное обновление выполняется само, если режим панели не совпадает с
 * запрошенным, база не загружена или накопился лимит частичных подряд.
 */
void display_eink_request_region(int16_t x, int16_t y, int16_t w, int16_t h);

/* Продвинуть автомат. Не блокирует (~1 мс максимум). Вызывать часто. */
void display_eink_poll(void);

/*
 * true, пока драйвер ещё может читать framebuffer. Менять framebuffer
 * (рендерить) можно, когда false: волна панели (секунды) уже идёт без
 * участия данных.
 */
bool display_eink_data_busy(void);

/* true, пока идёт обновление или есть невыполненный запрос. */
bool display_eink_is_busy(void);

/* Частичных обновлений подряд после последнего полного (диагностика, тесты). */
uint8_t display_eink_partial_count(void);

/* Блокирующее ожидание всех запрошенных обновлений (с ограничением по времени). */
void display_eink_wait(void);

/*
 * Блокирующе: display_eink_wait(), затем deep sleep панели.
 * Изображение на E-Ink остаётся без питания.
 */
void display_eink_sleep(void);

#endif /* DISPLAY_EINK_H */
