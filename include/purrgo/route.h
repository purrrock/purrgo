#ifndef PURRGO_ROUTE_H
#define PURRGO_ROUTE_H

/*
 * Пользовательский (заранее подготовленный) маршрут.
 *
 * Один GPX-файл из каталога ROUTES на SD читается потоком, из него берутся
 * точки <trkpt> и <rtept> (<wpt> игнорируются), точки сохраняются в RAM в
 * компактном виде и рисуются на карте отдельным стилем: чёрная линия 3 px с
 * белой линией 1 px по центру. Текущий записываемый трек (track_renderer.c)
 * остаётся тонкой чёрной линией и рисуется поверх маршрута.
 *
 * Расчёт маршрутов в PurrGO не выполняется.
 *
 * Если точек больше PURRGO_ROUTE_MAX_POINTS, выполняется прореживание по
 * расстоянию: минимальный шаг между сохранёнными точками растёт, пока всё не
 * поместится. Начало и конец каждого сегмента сохраняются всегда.
 */

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include "purrgo/gfx_renderer.h"
#include "purrgo/map.h"

/* Вместимость массива точек (8 байт на точку; признак разрыва занимает одну запись). */
#ifndef PURRGO_ROUTE_MAX_POINTS
#define PURRGO_ROUTE_MAX_POINTS 4096
#endif

/* Значение lat_1e7, помечающее разрыв между сегментами (<trkseg>, <trk>, <rte>). */
#define PURRGO_ROUTE_BREAK_LAT INT32_MIN

typedef struct {
    int32_t lat_1e7;
    int32_t lon_1e7;
} purrgo_route_point_t;

/* ------------------------------------------------------------------ */
/*  Потоковая загрузка (используется purrgo_route_load, доступна тестам) */
/* ------------------------------------------------------------------ */

/* Сбросить маршрут и разборщик: следующие purrgo_route_feed() начинают новый маршрут. */
void purrgo_route_begin(void);

/* Подать очередной фрагмент GPX (граница фрагмента может быть где угодно, в том числе внутри тега). */
void purrgo_route_feed(const char *chunk, size_t len);

/* Завершить разбор: дописать последнюю отброшенную точку и вычислить границы. */
void purrgo_route_end(void);

/* ------------------------------------------------------------------ */
/*  Загрузка из файла                                                   */
/* ------------------------------------------------------------------ */

/*
 * Читает GPX-файл filename (только имя, без пути) из каталога ROUTES.
 * true - загружена хотя бы одна линия (две точки в одном сегменте).
 * При ошибке маршрут очищается.
 */
bool purrgo_route_load(const char *filename);

/*
 * Приводит загруженный маршрут в соответствие с настройкой: пустое имя -
 * маршрута нет; то же имя, что уже загружено, - ничего не делает; иначе
 * загружает файл заново. Если прошлая попытка загрузить это имя не удалась
 * (например, SD ещё не была готова), она повторяется при следующем вызове.
 * Возвращает true, если маршрут загружен и может быть нарисован.
 */
bool purrgo_route_sync(const char *filename);

/* Убрать маршрут из памяти. */
void purrgo_route_clear(void);

/* ------------------------------------------------------------------ */
/*  Доступ к данным и отрисовка                                         */
/* ------------------------------------------------------------------ */

/* Число записей в массиве, включая признаки разрыва. */
size_t purrgo_route_entry_count(void);

/* Запись i; lat_1e7 == PURRGO_ROUTE_BREAK_LAT - разрыв сегмента. */
bool purrgo_route_get_entry(size_t i, purrgo_route_point_t *out);

/* Текущий минимальный шаг прореживания, 1e-7 градуса (0 - прореживания не было). */
uint32_t purrgo_route_decimation_step(void);

/*
 * Рисует маршрут в текущем clip-окне gfx. Слой выключается вызывающим кодом
 * (PURRGO_LAYER_ROUTE). Маршрут целиком вне камеры пропускается без проекции.
 */
void purrgo_route_render(
    gfx_context_t *gfx,
    const purrgo_bbox_t *camera,
    const purrgo_viewport_t *vp
);

#endif /* PURRGO_ROUTE_H */
