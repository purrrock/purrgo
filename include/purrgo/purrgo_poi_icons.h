/*
 * PurrGO 11x11 POI icons.
 *
 * Pixel format:
 *   bit 2    = alpha (0 transparent, 1 opaque)
 *   bits 1:0 = grayscale (0..3)
 *
 * Layout:
 *   purrgo_poi_icons[icon][row][column], 11 x 11 pixels, one byte per pixel.
 *
 * Icon selector is one byte: 0..255.
 *
 * Icon numbers:
 *   128..191  POI icons; the number is the PurrGO feature code of the POI
 *             class (see include/purrgo/map_style.h, docs/map-format-v3.md 8.1).
 *   35, 46, 47  UI icons (navigation target, waypoint, map centre crosshair).
 *             They are not feature codes and are never used by the pois layer.
 *   other     unused. Do not put a new POI icon below 128 or above 191.
 *
 * The data itself lives in src/core/purrgo_poi_icons.c (generated by
 * tools/purrgo_icon_editor11.py), so that this header does not pull ~31 KB
 * of constants into every translation unit that includes it.
 */

#ifndef PURRGO_POI_ICONS_H
#define PURRGO_POI_ICONS_H

#include <stdint.h>

#define PURRGO_POI_ICON_COUNT 256u
#define PURRGO_POI_ICON_WIDTH  11u
#define PURRGO_POI_ICON_HEIGHT 11u

#define PURRGO_POI_ALPHA 0x04u

extern const uint8_t purrgo_poi_icons[256][11][11];

#endif /* PURRGO_POI_ICONS_H */
