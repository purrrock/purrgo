#ifndef PURRGO_GPX_REPAIR_H
#define PURRGO_GPX_REPAIR_H

/*
 * Починка недописанных GPX-файлов.
 *
 * Файл трека обрывается без закрывающих тегов (</trkseg>, </trk>, </gpx>), если питание
 * пропало, не дождавшись purrgo_logger_stop(), а на SD успела попасть только часть данных
 * (чаще всего последняя точка оборвана посередине тега).
 *
 * Сканер читает файл потоком (тот же проход, что и разбор маршрута, без повторного чтения)
 * и следит за вложенностью элементов. Для починки нужны две вещи:
 *   - cut: смещение конца последнего "целого" места файла - закрывающего тега элемента
 *     не глубже gpx > X > Y (</trkpt>, </rtept>, </wpt>, </name>) либо начала структурного
 *     элемента gpx/trk/trkseg/rte. Всё после него (обрыв внутри точки, нули после сбоя
 *     питания) отбрасывается;
 *   - закрывающие теги для элементов, открытых на этот момент (в обратном порядке).
 *
 * Файл, закрытый тегом </gpx>, не ломается никогда; не-GPX файл (корневой элемент другой)
 * не трогается.
 */

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#define PURRGO_GPX_SCAN_DEPTH  3u    /* имена запоминаются для первых трёх уровней вложенности */
#define PURRGO_GPX_SCAN_NAME   16u   /* длина имени элемента с нулём */

typedef struct {
    uint32_t pos;                /* сколько байт подано */
    uint32_t cut;                /* смещение места обреза (после последнего целого тега) */
    uint8_t  depth;              /* текущая вложенность элементов */
    uint8_t  cut_depth;          /* вложенность в месте обреза (0 - места обреза ещё нет) */

    char     names[PURRGO_GPX_SCAN_DEPTH][PURRGO_GPX_SCAN_NAME];
    char     cut_names[PURRGO_GPX_SCAN_DEPTH][PURRGO_GPX_SCAN_NAME];

    char     tag[PURRGO_GPX_SCAN_NAME];
    uint8_t  tag_len;
    char     last_c;             /* последний символ внутри текущего тега (для "/>") */
    bool     in_tag;
    bool     name_done;          /* имя тега уже прочитано (дальше атрибуты) */
    bool     name_long;          /* имя не поместилось в tag */

    bool     root_seen;          /* встретился первый элемент */
    bool     is_gpx;             /* корневой элемент - gpx */
    bool     closed;             /* встретился </gpx> (или <gpx/>): файл считает себя законченным */
    bool     unsafe;             /* имя открытого элемента слишком длинное: закрыть его нельзя */
} purrgo_gpx_scan_t;

void purrgo_gpx_scan_init(purrgo_gpx_scan_t *s);

/* Подать очередной фрагмент файла (граница фрагмента может быть где угодно). */
void purrgo_gpx_scan_feed(purrgo_gpx_scan_t *s, const char *chunk, size_t len);

/* true - GPX-файл недописан и его можно починить. Вызывать после подачи всего файла. */
bool purrgo_gpx_scan_is_broken(const purrgo_gpx_scan_t *s);

/* Смещение, до которого файл нужно обрезать перед дозаписью закрывающих тегов. */
uint32_t purrgo_gpx_scan_cut_offset(const purrgo_gpx_scan_t *s);

/*
 * Текст для дозаписи после обреза: перевод строки и закрывающие теги, например
 * "\n</trkseg></trk>\n</gpx>\n". Возвращает длину (без нуля) или 0, если чинить нечего
 * или out мал.
 */
size_t purrgo_gpx_scan_fix_text(const purrgo_gpx_scan_t *s, char *out, size_t size);

/*
 * Чинит файл path по результату сканирования всего файла: обрезает хвост и дописывает
 * закрывающие теги. Перед правкой убеждается, что размер файла равен числу прочитанных
 * байт (иначе чтение могло оборваться по ошибке SD - обрезать нельзя).
 * Операция повторяема: если питание пропадёт посреди починки, файл останется целым
 * префиксом и будет починен при следующем открытии.
 * true - файл исправлен и записан на носитель.
 */
bool purrgo_gpx_repair_file(const char *path, const purrgo_gpx_scan_t *s);

#endif /* PURRGO_GPX_REPAIR_H */
