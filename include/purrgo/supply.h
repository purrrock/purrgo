#ifndef PURRGO_SUPPLY_H
#define PURRGO_SUPPLY_H

#include <stdbool.h>
#include <stdint.h>

/*
 * Контроль питания и запись на microSD.
 *
 * Модуль - единственный владелец состояния "запись на карту заблокирована".
 * Причин две, обе ведут к одной и той же остановке:
 *   1. VDD (выход TPS63802) упал ниже уровня, безопасного для записи на SD
 *      (платформа задаёт порог, STM32: PVD, apps/stm32/PurrGO_STM32U5/
 *      Core/Src/supply_pvd.c);
 *   2. напряжение батарей по АЦП ниже порога purrgo_supply_set_battery_stop_mv()
 *      (по умолчанию выключено: порог нужно подобрать по кривой разряда).
 * Остановка выполняется один раз, при переходе в состояние "заблокировано", и
 * не повторяется, когда вторая причина появляется следом. Карта, уже
 * размонтированная платформой по другим причинам, тоже не мешает: все шаги
 * безопасны при повторе.
 *
 * Когда запись блокируется, ядро:
 *   1. закрывает трек (футер GPX, f_close) - запись останавливается;
 *   2. закрывает файлы карты (purrgo_map_shutdown());
 *   3. просит платформу размонтировать карту (purrgo_platform_storage_suspend()).
 * Процессор и GNSS продолжают работать, пока хватает питания: приёмник не
 * выключается, экран и позиция обновляются. Пока питание "низкое", новые
 * файлы на карте не открываются, трек не стартует.
 *
 * Возврат к норме (например, подключили USB 5 В): после PURRGO_SUPPLY_RECOVER_MS
 * непрерывно нормального напряжения запись разрешается снова; карту платформа
 * монтирует сама, трек стартует как новая сессия (новый файл).
 */

/* Низкое напряжение должно держаться столько, мс, прежде чем сработает остановка:
 * короткие просадки (всплеск тока E-Ink, GNSS) игнорируются. */
#ifndef PURRGO_SUPPLY_LOW_CONFIRM_MS
#define PURRGO_SUPPLY_LOW_CONFIRM_MS 50u
#endif

/* Нормальное напряжение должно держаться столько, мс, прежде чем запись снова разрешена. */
#ifndef PURRGO_SUPPLY_RECOVER_MS
#define PURRGO_SUPPLY_RECOVER_MS 5000u
#endif

/*
 * Платформенный хук: true - VDD ниже порога безопасной записи на SD.
 * STM32: флаг PVDO. PC: всегда false.
 */
bool purrgo_platform_supply_low(void);

/*
 * Платформенный хук: размонтировать карту и больше её не трогать до
 * восстановления напряжения (без записи на карту). Вызывается после закрытия
 * всех файлов. STM32: sd_card.c; аппаратное отключение питания карты - позже,
 * через ключ нагрузки.
 */
void purrgo_platform_storage_suspend(void);

/* Гистерезис порога по АЦП, мВ: запись разрешается при напряжении батарей не ниже порог + гистерезис. */
#ifndef PURRGO_SUPPLY_BATT_HYST_MV
#define PURRGO_SUPPLY_BATT_HYST_MV 150u
#endif

/* Период опроса АЦП-причины, мс (платформа сама кэширует замер). */
#ifndef PURRGO_SUPPLY_BATT_POLL_MS
#define PURRGO_SUPPLY_BATT_POLL_MS 1000u
#endif

/* Порог по умолчанию, мВ напряжения блока батарей (PURRGO_BATTERY_CELLS элементов); 0 - выключен. */
#ifndef PURRGO_SUPPLY_BATT_STOP_MV
#define PURRGO_SUPPLY_BATT_STOP_MV 0u
#endif

/*
 * Порог остановки записи по напряжению блока батарей (АЦП), мВ; 0 - не использовать.
 * Не действует при питании 5 В и пока напряжение не измерено.
 */
void purrgo_supply_set_battery_stop_mv(uint16_t mv);

/* Периодический опрос из purrgo_app_tick(). true - состояние блокировки изменилось. */
bool purrgo_supply_tick(uint32_t now_ms);

/* true - запись на карту заблокирована из-за низкого напряжения. */
bool purrgo_supply_storage_blocked(void);

/* Забыть состояние (инициализация приложения, тесты). */
void purrgo_supply_reset(void);

#endif /* PURRGO_SUPPLY_H */
