#ifndef PURRGO_SUPPLY_H
#define PURRGO_SUPPLY_H

#include <stdbool.h>
#include <stdint.h>

/*
 * Контроль питания и запись на microSD.
 *
 * Модуль - единственный владелец состояния "запись на карту заблокирована".
 * Причин две, обе ведут к одной и той же остановке:
 *   1. VDD (выход TPS63802) упал ниже уровня, безопасного для записи на SD
 *      (платформа задаёт порог, STM32: PVD, stm32/
 *      Core/Src/supply_pvd.c);
 *   2. напряжение батарей по АЦП ниже порога для выбранного источника питания
 *      (purrgo_battery_stop_mv(): солевые - 1000 мВ на элемент, Li-ion AA -
 *      900 мВ на элемент; для остальных источников порога нет, пока не снята
 *      кривая разряда).
 * Остановка выполняется один раз, при переходе в состояние "заблокировано", и
 * не повторяется, когда вторая причина появляется следом.
 *
 * Когда запись блокируется, ядро закрывает трек (футер GPX, f_close): запись
 * останавливается, новые сессии не стартуют. Дальше любая запись на карту
 * (трек, PURRGO.CFG, файлы точек) отклоняется. Карта при этом НЕ размонтируется
 * и файлы карты местности остаются открытыми: чтение продолжается, карта
 * подгружается и книги читаются. Процессор и GNSS тоже работают, пока хватает
 * питания: приёмник не выключается, экран и позиция обновляются.
 *
 * Возврат к норме:
 *   - причина 1 (PVD): после PURRGO_SUPPLY_RECOVER_MS непрерывно нормального
 *     напряжения запись разрешается, трек стартует как новая сессия (новый файл);
 *   - причина 2 (батареи): остаётся до смены источника питания в меню (например,
 *     на 5 В) или до перезапуска: у почти севшей батареи напряжение отскакивает
 *     после снятия нагрузки, и возврат по гистерезису давал бы цикл
 *     "стоп - старт - стоп" с новым файлом трека на каждом витке.
 */

/* Низкое напряжение должно держаться столько, мс, прежде чем сработает остановка:
 * короткие просадки (всплеск тока E-Ink, GNSS) игнорируются. */
#ifndef PURRGO_SUPPLY_LOW_CONFIRM_MS
#define PURRGO_SUPPLY_LOW_CONFIRM_MS 50u
#endif

/* Нормальное напряжение (по PVD) должно держаться столько, мс, прежде чем запись снова разрешена. */
#ifndef PURRGO_SUPPLY_RECOVER_MS
#define PURRGO_SUPPLY_RECOVER_MS 5000u
#endif

/*
 * Платформенный хук: true - VDD ниже порога безопасной записи на SD.
 * STM32: флаг PVDO. PC: всегда false.
 */
bool purrgo_platform_supply_low(void);

/* Период опроса АЦП-причины, мс (платформа сама кэширует замер). */
#ifndef PURRGO_SUPPLY_BATT_POLL_MS
#define PURRGO_SUPPLY_BATT_POLL_MS 1000u
#endif

/* Сколько опросов подряд напряжение батарей должно быть ниже порога: один замер
 * в момент всплеска тока (E-Ink, GNSS) блокировку не включает. */
#ifndef PURRGO_SUPPLY_BATT_CONFIRM_POLLS
#define PURRGO_SUPPLY_BATT_CONFIRM_POLLS 3u
#endif

/* Периодический опрос из purrgo_app_tick(). true - состояние блокировки изменилось. */
bool purrgo_supply_tick(uint32_t now_ms);

/* true - запись на карту заблокирована из-за низкого напряжения. */
bool purrgo_supply_storage_blocked(void);

/* Забыть состояние (инициализация приложения, тесты). */
void purrgo_supply_reset(void);

#endif /* PURRGO_SUPPLY_H */
