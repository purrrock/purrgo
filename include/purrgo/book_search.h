#ifndef PURRGO_BOOK_SEARCH_H
#define PURRGO_BOOK_SEARCH_H

/*
 * Сопоставление текста для поиска в книге (читалка, book_reader.h).
 *
 * Модуль чистый: без файлов, памяти и состояния. Текст страницы и запрос лежат
 * в кодировке PurrGO-256 (docs/PurrGO_font_encoding.md), то есть в той же, в
 * которой книга записана на SD и в которой экранная клавиатура (keyboard.h)
 * возвращает набранную строку; перекодировка не нужна.
 *
 * Правила сравнения:
 *   - регистр не учитывается: латиница, кириллица (А-Я, Ґ Є І Ї Ў Ђ Ј Љ Њ Џ Ѓ Ѕ Ғ Қ Ң Ұ);
 *   - Е и Ё считаются одной буквой (в книгах и запросах "е" вместо "ё" - обычное дело);
 *   - пробел запроса совпадает с любой непустой серией пробелов и переводов
 *     строки в тексте: найденная фраза может занимать несколько строк страницы
 *     (текст уже разбит на строки, LF - единственный разделитель строк);
 *   - перенос слова: если строка кончается на '-', то слово может быть записано
 *     в запросе слитно ("пример" находит "при-" LF "мер"); дефис в запросе тоже
 *     находит дефис на конце строки ("кое-что" находит "кое-" LF "что");
 *   - совпадение не может начинаться с переноса и пробела: запрос подготавливается
 *     purrgo_book_search_prepare() (края обрезаются, серии пробелов сворачиваются).
 *
 * Совпадение, начавшееся на странице, может продолжаться на следующей: вызывающий
 * дописывает в конец буфера LF и начало следующей страницы (см. text_len и hi).
 */

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#include "purrgo/keyboard.h"

/* Наибольшая длина запроса в байтах PurrGO-256 (как у ввода с клавиатуры). */
#define PURRGO_BOOK_SEARCH_MAX PURRGO_KBD_TEXT_MAX

/* Запас байт сверх длины запроса в хвосте следующей страницы (переносы "-" LF). */
#define PURRGO_BOOK_SEARCH_TAIL_SLACK 8u

/* Символ PurrGO-256, приведённый к виду для сравнения (нижний регистр, Ё -> е). */
uint8_t purrgo_book_search_fold(uint8_t c);

/*
 * Запрос для сравнения из набранной строки: символы приводятся функцией
 * purrgo_book_search_fold(), пробелы по краям отбрасываются, серии пробелов
 * сворачиваются в один. Результат завершён нулём. Возвращает длину (0 - пустой
 * запрос, искать нечего). typed == NULL даёт пустой запрос.
 */
size_t purrgo_book_search_prepare(const char *typed, uint8_t out[PURRGO_BOOK_SEARCH_MAX + 1u]);

/*
 * Первое совпадение запроса pat (подготовленного prepare) в text[0, text_len),
 * начало которого лежит в [lo, hi). Само совпадение может выходить за hi, но не
 * за text_len. В *match_start - позиция первого байта, в *match_end - позиция
 * за последним (оба необязательны). true, если совпадение есть.
 */
bool purrgo_book_search_find(const uint8_t *text, size_t text_len, size_t lo, size_t hi,
                             const uint8_t *pat, size_t pat_len,
                             size_t *match_start, size_t *match_end);

/* То же, но самое последнее совпадение (с наибольшим началом) в [lo, hi). */
bool purrgo_book_search_find_last(const uint8_t *text, size_t text_len, size_t lo, size_t hi,
                                  const uint8_t *pat, size_t pat_len,
                                  size_t *match_start, size_t *match_end);

#endif /* PURRGO_BOOK_SEARCH_H */
