#ifndef PURRGO_MAP_INTERNAL_H
#define PURRGO_MAP_INTERNAL_H

#include <stdint.h>

/*
 * Shared map subsystem constants and diagnostics.
 */

#define PURRGO_MAP_MAX_PARTS 32
/*
 * Максимум точек в одном объекте (сумма по всем частям). Совпадает с пределом
 * компилятора карт: way в OSM - до 1999 узлов, мультиполигон ограничен тем же
 * числом. Объект больше лимита map_mlp_iter_init() отвергает целиком, поэтому
 * при меньшем лимите длинные реки и большие озёра пропадают с карты. Цена -
 * статический буфер s_polygon_buffer в map_render.c: 8 байт на точку.
 */
#define PURRGO_MAP_MAX_POINTS 2000
/* Размер сектора SD/FatFs; геометрия читается порциями до 512 байт. */
#define PURRGO_MAP_READ_CHUNK_SIZE 512u

/*
 * Read-ahead для .mlp: максимум секторов за один многосекторный запрос к SD при промахе
 * кэша. На 500 м - 5 км геометрия читается подряд, и блок из нескольких секторов дешевле,
 * чем столько же одиночных запросов (на реальных картах Беларуси -10...-20% времени
 * ввода-вывода). На 10 км и крупнее (замер 0008, PROF3) объекты читаются прыжками, и
 * фиксированный блок 4 сектора читает 2-3 лишних сектора на промах (235 мкс на сектор при SPI
 * 20 МГц).
 *
 * PURRGO_MAP_MLP_ADAPTIVE_RA 1: адаптивный режим, как для .idx (блок 1 -> 2 -> 4, растёт только
 * пока промахи идут подряд). 0 (по умолчанию): фиксированный блок. Замер на железе (prof1.log):
 * адаптивный режим читает на 15-30% меньше секторов, но на 30-50% больше команд (441 мкс на
 * команду ~ 1,9 сектора), итог по времени кадра в пределах шума или чуть хуже.
 */
#define PURRGO_MAP_MLP_READ_AHEAD_SECTORS 4u
#ifndef PURRGO_MAP_MLP_ADAPTIVE_RA
#define PURRGO_MAP_MLP_ADAPTIVE_RA 0
#endif

/*
 * Адаптивный read-ahead для .idx (purrgo_fs_set_adaptive_read_ahead): максимум секторов
 * в блоке. На мелких масштабах обход индекса идёт прыжками (по замерам 26-32% промахов
 * подряд) и блок остаётся одним сектором; на масштабах 10-11 промахи подряд 89-93%, и блок
 * растёт 2, 4, 8 секторов (команда SD на 8 секторов ~2,3 мс против ~5,4 мс на 8 одиночных).
 */
#define PURRGO_MAP_IDX_READ_AHEAD_MAX_SECTORS 8u

/*
 * Кэш секторов SD в арене режима карты (purrgo_fs_cache_attach): записей по 512 Б. Хватает на
 * весь индекс кадра на мелких масштабах (~470 секторов, замер для V3; для V4 перемерить) с запасом, так что повторный рисунок
 * того же вида и перекрывающиеся виды читаются из RAM. Требует purrgo_fs_cache_bytes(N)
 * байт арены (~400 КБ при 768); остаток арены отдаётся диагностике (purrgo/render_prof.h).
 */
#define PURRGO_MAP_CACHE_SECTORS 768u

/*
 * Порог пропуска мелких объектов: если обе стороны bbox объекта меньше порога
 * в пикселях экрана, его геометрия не читается и не рисуется (на дальних
 * масштабах это десятки процентов объектов и столько же чтений с SD).
 * Для линий пропуск отключён: дорога в OSM состоит из множества коротких
 * way (разбиение на перекрёстках), и каждый из них - звено цепочки. Если
 * пропустить короткое звено, в дороге остаётся разрыв (толстые линии 2-3 px
 * за счёт "шапок" на концах перекрывали бы такие щели, но только когда звено
 * нарисовано). Экономия на линиях мала, разрывы заметны.
 * 0 отключает пропуск.
 */
#define PURRGO_MAP_MIN_PX_LINE    1
#define PURRGO_MAP_MIN_PX_POLYGON 3

/*
 * Формат карты PurrGO V4 (docs/map-format-v4.md). Формат V3 не поддерживается.
 */
#define PURRGO_MAP_LOD_COUNT        4u
/* Блок индекса и сектор заголовка SQT: ровно один сектор SD. */
#define PURRGO_MAP_BLOCK_SIZE       512u
#define PURRGO_MAP_NAV_NODE_SIZE    28u
#define PURRGO_MAP_DATA_NODE_SIZE   25u
#define PURRGO_MAP_NAV_FANOUT       18u   /* навигационных узлов в блоке (18 * 28 = 504 Б) */
#define PURRGO_MAP_LEAF_FANOUT      20u   /* узлов данных в блоке (20 * 25 = 500 Б) */
/* Первая секция LOD в .idx: за заголовком PGO идёт заполнение до границы сектора. */
#define PURRGO_MAP_FIRST_LOD_OFFSET 0x200u
#define PURRGO_MAP_SQT_TOPOLOGY     2u

/*
 * Предел глубины дерева индекса (число уровней навигационных узлов). Задаёт читатель,
 * не формат: при ветвлении 18/20 восемь уровней вмещают более 10^10 объектов, а реальная
 * карта Беларуси имеет глубину 4. Дерево читается с SD-карты, то есть из недоверенных
 * данных: предел ограничивает рекурсию обхода (кадр стека на уровень ~200 Б) и память.
 */
#define PURRGO_MAP_MAX_TREE_DEPTH   8u

/* Поле названия в записи .db (раздел 10): 100 байт, PurrGO-256, добито нулями. */
#define PURRGO_MAP_NAME_FIELD_SIZE  100u
/* Подпись на карте (раздел 10.6.1): до 22 символов, длиннее - 20 символов и "..". */
#define PURRGO_MAP_LABEL_MAX        22u
#define PURRGO_MAP_LABEL_CUT        20u

typedef struct {
    uint8_t  file_type;
    uint32_t payload_size;
    uint32_t file_end;                        /* 32 + payload_size */
    uint32_t lod_offset[PURRGO_MAP_LOD_COUNT];/* только для .idx */
} pgo_header_info_t;

/* Секция LOD индекса: разобранный сектор заголовка SQT (раздел 5). */
typedef struct {
    uint32_t start;        /* смещение секции в файле */
    uint32_t size;         /* размер секции в байтах */
    uint32_t depth;        /* число уровней навигационных узлов; 0 - пустой LOD */
    uint32_t root_count;   /* навигационных узлов в корневом блоке */
    uint32_t nav_fanout;
    uint32_t leaf_fanout;
} map_section_t;

/* Little-endian helpers */
static inline int32_t unpack_i32_le(const uint8_t *buf)
{
    return (int32_t)(
        (uint32_t)buf[0] |
        ((uint32_t)buf[1] << 8) |
        ((uint32_t)buf[2] << 16) |
        ((uint32_t)buf[3] << 24)
    );
}

static inline uint32_t unpack_u32_le(const uint8_t *buf)
{
    return
        (uint32_t)buf[0] |
        ((uint32_t)buf[1] << 8) |
        ((uint32_t)buf[2] << 16) |
        ((uint32_t)buf[3] << 24);
}

/*
 * Память режима карты: занимает арену (purrgo/ram_arena.h) и подключает кэш секторов.
 * Вызывается в начале каждого кадра, дёшево, если арена уже у карты. Если арену заняла
 * читалка, она закрывается (книга открывается заново при возврате в режим книги).
 */
void map_ram_enter(void);

#endif // PURRGO_MAP_INTERNAL_H
