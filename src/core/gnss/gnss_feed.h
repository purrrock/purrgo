#ifndef PURRGO_GNSS_FEED_H
#define PURRGO_GNSS_FEED_H

#include <stdbool.h>
#include <stdint.h>

#include "purrgo/gnss.h"
#include "purrgo/gnss_ubx.h"
#include "purrgo/gnss_types.h"
#include "purrgo/hardware_config.h"

/*
 * Живое состояние приёмника: разбор потока байт (NMEA вперемешку с бинарными
 * кадрами UBX), текущее решение, счётчик принятых решений и таймаут фикса
 * ("приёмник замолчал - позиции нет"). Раньше всё это жило в app_fsm.c; теперь
 * app_fsm.c только подаёт байты, выбирает срок таймаута (он зависит от экрана
 * трекера) и читает решение. Модуль не знает ни экранов, ни логгера.
 * Проверяется host-тестом tests/host/test_gnss_feed.c.
 *
 * Время берётся из purrgo_system_time_ms() в момент приёма решения: байты
 * разбираются в прерываниях/цикле платформы, отдельного "now" у вызывающего нет.
 */
/*
 * Таймаут фикса: если решение (PVT или RMC) не приходило дольше этого времени,
 * позиция считается невалидной (приёмник молчит, антенна отключена и т.п.).
 * Переопределяется из сборки. Срок для трекера с PSMOO длиннее и задаёт его вызывающий.
 */
#ifndef PURRGO_GNSS_FIX_TIMEOUT_MS
#define PURRGO_GNSS_FIX_TIMEOUT_MS 5000U
#endif

typedef struct {
    purrgo_gnss_solution_t solution;   /* текущее решение приёмника */
    purrgo_gnss_parser_t nmea;
#if PURRGO_GNSS_UBX
    purrgo_ubx_parser_t ubx;
#endif
    /* Когда пришло последнее решение (PVT или RMC): признак, что приёмник жив. */
    uint32_t last_rx_ms;
    /* Когда в последний раз проверяли таймаут: нужно, чтобы заметить простой главного цикла. */
    uint32_t last_check_ms;
    /*
     * Растёт на каждое новое решение приёмника (PVT или RMC). В трекере с PSMOO решения
     * приходят раз в период, а устаревший фикс остаётся действующим до таймаута; по счётчику
     * потребитель отличает свежее решение от повторного чтения прежнего (логгер получает
     * фикс один раз, а не каждую секунду, иначе при PURRGO_TRACK_DIAG он писал бы в GPX
     * "отброшенные" копии).
     */
    uint32_t fix_seq;
} purrgo_gnss_feed_t;

/*
 * Начало работы: разборщики сброшены, отсчёт молчания приёмника идёт от now_ms.
 * Решение и счётчик решений НЕ сбрасываются намеренно (как и при повторной
 * инициализации приложения раньше: статическая память переживала её).
 */
void purrgo_gnss_feed_init(purrgo_gnss_feed_t *f, uint32_t now_ms);

/* Принять очередной байт потока приёмника. */
void purrgo_gnss_feed_byte(purrgo_gnss_feed_t *f, uint8_t byte);

/* Решение "нет фикса": позиция, курс, скорость и оценки точности невалидны. */
void purrgo_gnss_feed_invalidate(purrgo_gnss_feed_t *f);

/* Молчание приёмника отсчитывается заново (смена режима, приёмнику нужно время на решение). */
void purrgo_gnss_feed_restart_silence(purrgo_gnss_feed_t *f, uint32_t now_ms);

/* То же, и счётчик простоя главного цикла начинается заново (возврат из читалки/трекера). */
void purrgo_gnss_feed_restart(purrgo_gnss_feed_t *f, uint32_t now_ms);

/*
 * Раз в такт главного цикла: сбрасывает валидность позиции, если приёмник молчит
 * дольше timeout_ms. Если главный цикл сам простоял дольше timeout_ms / 2 (блокирующее
 * обновление e-ink занимает секунды; порог привязан к тому же параметру, что и срок), молчание оценить нельзя - байты ждут в буфере DMA, - и срок
 * дается заново, чтобы не мигать "нет фикса" после каждого полного обновления.
 */
void purrgo_gnss_feed_check_timeout(purrgo_gnss_feed_t *f, uint32_t now_ms, uint32_t timeout_ms);

#endif /* PURRGO_GNSS_FEED_H */
