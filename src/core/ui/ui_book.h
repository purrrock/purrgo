#ifndef PURRGO_UI_BOOK_H
#define PURRGO_UI_BOOK_H

#include "purrgo/gfx_renderer.h"

/*
 * Экраны читалки (book_reader.h). Режим дисплея - 1 bit: рисуются только
 * чёрный и белый.
 *
 * Страница: верхняя строка (8 px) - инверсная строка статуса "страница/всего,
 * заряд батареи" (заряд опрашивается раз в минуту, процент прочитанного не
 * выводится), остальные 32 строки по 8 px - текст страницы, 29 символов по 6 px
 * (геометрия PGB 1.0). Подсказок кнопок на экране чтения нет: он целиком занят
 * текстом.
 */

/* Сброс слежения за строками списка (вход на экран). */
void ui_book_list_reset(void);

void ui_render_book_list(gfx_context_t* gfx);

/*
 * Сброс слежения за содержимым экрана чтения: следующий ui_render_book_read()
 * рисует кадр целиком (вход на экран, смена режима, полное обновление).
 */
void ui_book_read_reset(void);

/*
 * Экран чтения. Если с прошлого вызова ничего не изменилось, не рисует и не
 * запрашивает обновление дисплея; если изменилась только строка статуса
 * (заряд, переход по процентам) - обновляет только её; иначе - весь экран.
 */
void ui_render_book_read(gfx_context_t* gfx);

#endif /* PURRGO_UI_BOOK_H */
