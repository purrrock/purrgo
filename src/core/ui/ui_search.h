#ifndef PURRGO_UI_SEARCH_H
#define PURRGO_UI_SEARCH_H

#include "purrgo/gfx_renderer.h"

/*
 * Экран умного поиска (APP_STATE_SEARCH, логика - purrgo/search_screen.h). Раскладка 176x264 - как у
 * экранной клавиатуры (ui_keyboard.h), свободная область y 34..143 занята результатами:
 *   y  34..45   строка состояния ("Searching...", "5 found", "12/32 GNSS", подсказка по вводу);
 *   y  46..141  8 строк списка: значок слоя, название, расстояние и направление;
 * внизу сетка клавиш и подсказки кнопок (зависят от того, где фокус - на клавиатуре или на списке).
 * Частичное обновление - как у клавиатуры и списков меню: регистрируются только изменившиеся строки.
 */

/* Сброс слежения за изменениями (вход на экран). */
void ui_search_reset(void);

void ui_render_search(gfx_context_t *gfx);

#endif /* PURRGO_UI_SEARCH_H */
