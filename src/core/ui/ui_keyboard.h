#ifndef PURRGO_UI_KEYBOARD_H
#define PURRGO_UI_KEYBOARD_H

#include "purrgo/gfx_renderer.h"
#include "purrgo/keyboard.h"

/*
 * Экран экранной клавиатуры (логика - purrgo/keyboard.h). Режим дисплея -
 * 1 bit (DISPLAY_MODE_MONO): рисуются только чёрный и белый.
 *
 * Раскладка экрана 176x264:
 *
 *   y   0..11   заголовок слева, раскладка и состояние Shift справа
 *   y  14..29   поле ввода (хвост строки, если она длиннее поля)
 *   y  34..143  свободная область (результаты поиска и т.п.): ui_render_keyboard()
 *               оставляет её пустой, вызывающий код при необходимости рисует
 *               в ней после вызова и сам регистрирует обновление этой области
 *   y 148..238  сетка клавиш (5 строк по 18 px, все клавиши в рамке, общие линии)
 *   y 244..261  подсказки кнопок
 *
 * Частичное обновление: после первого кадра (или ui_keyboard_reset()) функция
 * регистрирует через display_refresh_region() только изменившееся - две клавиши
 * при движении курсора, поле ввода при наборе, сетку и строку состояния при смене
 * раскладки или Shift. Первый кадр после reset ничего не регистрирует: экран при
 * входе обновляется целиком (смена режима/экрана), как у остальных экранов.
 */

#define UI_KEYBOARD_FREE_TOP_PX     34
#define UI_KEYBOARD_FREE_BOTTOM_PX  144   /* первая строка экрана ниже свободной области */
#define UI_KEYBOARD_GRID_TOP_PX     148

/* Сброс слежения за изменениями (вход на экран). */
void ui_keyboard_reset(void);

void ui_render_keyboard(gfx_context_t *gfx, const purrgo_keyboard_t *kb);

#endif /* PURRGO_UI_KEYBOARD_H */
