#define PGO_MAP_COUNT (sizeof(k_pgo_map) / sizeof(k_pgo_map[0]))
#define PGO_UNKNOWN   0x3Fu

uint8_t purrgo_unicode_to_pgo(uint32_t codepoint)
{
    if (codepoint < 0x80u) {
        return (uint8_t)codepoint;
    }
    if (codepoint > 0xFFFFu) {
        return PGO_UNKNOWN;
    }

    size_t lo = 0;
    size_t hi = PGO_MAP_COUNT;
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2u;
        uint16_t cp = k_pgo_map[mid].cp;
        if (cp == codepoint) {
            return k_pgo_map[mid].pgo;
        }
        if (cp < codepoint) {
            lo = mid + 1u;
        } else {
            hi = mid;
        }
    }
    return PGO_UNKNOWN;
}

/*
 * Читает один символ UTF-8. Возвращает число израсходованных байт (>= 1).
 * Отвергает обрезанные, "переполненные" (overlong) и суррогатные
 * последовательности: тогда *cp = 0xFFFFFFFF, расходуется один байт.
 */
static size_t utf8_next(const unsigned char *s, uint32_t *cp)
{
    unsigned char c = s[0];

    if (c < 0x80u) {
        *cp = c;
        return 1;
    }

    size_t   len;
    uint32_t value;
    uint32_t min;

    if ((c & 0xE0u) == 0xC0u) {
        len = 2; value = c & 0x1Fu; min = 0x80u;
    } else if ((c & 0xF0u) == 0xE0u) {
        len = 3; value = c & 0x0Fu; min = 0x800u;
    } else if ((c & 0xF8u) == 0xF0u) {
        len = 4; value = c & 0x07u; min = 0x10000u;
    } else {
        *cp = 0xFFFFFFFFu;
        return 1;
    }

    for (size_t i = 1; i < len; i++) {
        if ((s[i] & 0xC0u) != 0x80u) { /* в т.ч. конец строки (s[i] == 0) */
            *cp = 0xFFFFFFFFu;
            return 1;
        }
        value = (value << 6) | (s[i] & 0x3Fu);
    }

    if (value < min || value > 0x10FFFFu || (value >= 0xD800u && value <= 0xDFFFu)) {
        *cp = 0xFFFFFFFFu;
        return 1;
    }

    *cp = value;
    return len;
}

size_t purrgo_utf8_to_pgo(const char *src, char *dst, size_t dst_size)
{
    if (!dst || dst_size == 0) {
        return 0;
    }
    if (!src) {
        dst[0] = '\0';
        return 0;
    }

    const unsigned char *s = (const unsigned char *)src;
    size_t n = 0;

    while (*s != 0 && n + 1 < dst_size) {
        uint32_t cp;
        s += utf8_next(s, &cp);
        dst[n++] = (char)((cp == 0xFFFFFFFFu) ? PGO_UNKNOWN : purrgo_unicode_to_pgo(cp));
    }
    dst[n] = '\0';
    return n;
}

void purrgo_utf8_to_pgo_inplace(char *str)
{
    if (!str) {
        return;
    }

    const unsigned char *s = (const unsigned char *)str;
    char *d = str;

    while (*s != 0) {
        uint32_t cp;
        s += utf8_next(s, &cp);
        *d++ = (char)((cp == 0xFFFFFFFFu) ? PGO_UNKNOWN : purrgo_unicode_to_pgo(cp));
    }
    *d = '\0';
}
