#include "purrgo/gnss_io.h"

#include <stddef.h>
#include <stdint.h>

/*
 * Временный GNSS MOCK для STM32.
 *
 * Этот код не использует UART и не зависит от конкретного GNSS-модуля.
 * Он имитирует входной последовательный поток NMEA.
 *
 * В дальнейшем вместо этого массива будет использоваться реальный
 * транспорт GNSS (UART/DMA), а интерфейс purrgo_gnss_read_byte()
 * останется неизменным.
 *
 * Используем две стандартные NMEA-строки:
 *
 *   GPRMC — время, дата, координаты, скорость.
 *   GPGGA — координаты, качество fix, число спутников, высота.
 *
 * Контрольные суммы проверены для каждой строки.
 */
static const char gnss_mock_stream[] =
    "$GPRMC,123456,A,5342.8100,N,02825.1940,E,2.69,0.0,010124,,,A*44\r\n"
    "$GPGGA,123456,5342.8100,N,02825.1940,E,1,09,1.0,150.0,M,0.0,M,,*71\r\n";

/*
 * Текущая позиция в MOCK-потоке.
 *
 * После достижения '\0' поток начинается сначала.
 */
static size_t gnss_mock_position = 0U;


/**
 * @brief Прочитать один байт из STM32 GNSS-потока.
 *
 * Сейчас функция возвращает байты из тестового NMEA MOCK.
 *
 * @param[out] byte
 *     Адрес переменной, куда будет записан очередной байт.
 *
 * @return true
 *     Если байт получен.
 *
 * @return false
 *     Если входной поток временно не содержит данных.
 *
 * Для текущего MOCK false практически не возникает:
 * после окончания строки поток начинается сначала.
 */
bool purrgo_gnss_read_byte(uint8_t *byte)
{
    if (byte == NULL)
    {
        return false;
    }

    /*
     * Получаем текущий символ.
     */
    const char current = gnss_mock_stream[gnss_mock_position];

    /*
     * Конец строки-массива.
     *
     * После него начинаем MOCK-поток заново.
     */
    if (current == '\0')
    {
        gnss_mock_position = 0U;
    }

    /*
     * Возвращаем очередной байт.
     */
    *byte = (uint8_t)gnss_mock_stream[gnss_mock_position];

    /*
     * Переходим к следующему байту.
     */
    gnss_mock_position++;

    return true;
}