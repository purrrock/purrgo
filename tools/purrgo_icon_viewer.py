#!/usr/bin/env python3
"""PurrGO POI/UI icon viewer.

Reads src/core/purrgo_poi_icons.c (generated by purrgo_icon_editor11.py) and
renders all icons into a PNG preview.

Format (see include/purrgo/purrgo_poi_icons.h):
    const uint8_t purrgo_poi_icons[N][H][W]   (now 256 x 11 x 11), one byte per pixel
      bit 2    = alpha (0 transparent, 1 opaque)
      bits 1:0 = grayscale 0..3 (0 black ... 3 white)
Icon numbers: 128..191 POI (feature codes), 192..223 UI icons.
"""

import argparse
import math
import re
import sys
from pathlib import Path

import numpy as np
import matplotlib

ALPHA_BIT = 0x04
DEFAULT_SRC = Path(__file__).resolve().parent.parent / "src" / "core" / "purrgo_poi_icons.c"

# 4-level E-Ink palette (0..3), same as in purrgo_icon_editor11.py
PALETTE = np.array([0, 85, 170, 255], dtype=np.uint8)
BG_TRANSPARENT = (217, 217, 217)   # light gray, imitates landuse fill


def parse_icons(text):
    """Return an array [N, H, W] of raw pixel bytes."""
    # Declaration with dimensions: purrgo_poi_icons[N][H][W] = { ... };
    m = re.search(r'purrgo_poi_icons\s*\[\s*(\w+)\s*\]\s*\[\s*(\w+)\s*\]\s*\[\s*(\w+)\s*\]'
                  r'\s*=\s*\{(.*?)\n\};', text, re.DOTALL)
    if not m:
        raise ValueError("массив purrgo_poi_icons[N][H][W] не найден")
    try:
        n, h, w = (int(m.group(i), 0) for i in (1, 2, 3))
    except ValueError:
        raise ValueError("размеры массива должны быть числами в исходнике (не макросами)")

    body = re.sub(r'/\*.*?\*/', '', m.group(4), flags=re.DOTALL)   # комментарии /* Icon N */
    body = re.sub(r'//[^\n]*', '', body)
    values = [int(v, 16) for v in re.findall(r'0x[0-9A-Fa-f]{1,2}', body)]

    if len(values) != n * h * w:
        raise ValueError(f"ожидалось {n}*{h}*{w}={n*h*w} значений, найдено {len(values)}")
    return np.array(values, dtype=np.uint8).reshape((n, h, w))


def render(icons, cols, scale, pad, only_used):
    n, h, w = icons.shape
    indices = [i for i in range(n) if not only_used or (icons[i] & ALPHA_BIT).any()]
    if not indices:
        raise ValueError("нет ни одной непустой иконки")

    rows = math.ceil(len(indices) / cols)
    cols = min(cols, len(indices))
    cell_w = w * scale + pad
    cell_h = h * scale + pad
    canvas = np.empty((rows * cell_h, cols * cell_w, 3), dtype=np.uint8)
    canvas[:] = BG_TRANSPARENT

    for k, idx in enumerate(indices):
        r, c = divmod(k, cols)
        y0 = r * cell_h + pad // 2
        x0 = c * cell_w + pad // 2
        icon = icons[idx]
        for y in range(h):
            for x in range(w):
                v = int(icon[y, x])
                if v & ALPHA_BIT:
                    g = PALETTE[v & 0x03]
                    canvas[y0 + y * scale:y0 + (y + 1) * scale,
                           x0 + x * scale:x0 + (x + 1) * scale] = g
    return canvas, indices, cols, rows, cell_w, cell_h


def main():
    ap = argparse.ArgumentParser(description="PurrGO icon preview")
    ap.add_argument("source", nargs="?", default=str(DEFAULT_SRC),
                    help="purrgo_poi_icons.c (по умолчанию src/core/purrgo_poi_icons.c)")
    ap.add_argument("-o", "--output", default="purrgo_icons_preview.png")
    ap.add_argument("--cols", type=int, default=16, help="иконок в строке (16)")
    ap.add_argument("--scale", type=int, default=4, help="масштаб пикселя (4)")
    ap.add_argument("--all", action="store_true", help="показать и пустые иконки")
    ap.add_argument("--labels", action="store_true", help="подписать номера иконок")
    ap.add_argument("--no-show", action="store_true", help="только сохранить PNG")
    args = ap.parse_args()

    if args.no_show:
        matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    try:
        text = Path(args.source).read_text(encoding="utf-8")
    except OSError as e:
        sys.exit(f"Ошибка: не удалось прочитать '{args.source}': {e}")
    try:
        icons = parse_icons(text)
    except ValueError as e:
        sys.exit(f"Ошибка: {e}")

    pad = 4 if not args.labels else 12
    canvas, indices, cols, rows, cw, ch = render(icons, args.cols, args.scale, pad, not args.all)
    n, h, w = icons.shape

    fig_w = max(5.0, canvas.shape[1] / 50)
    fig_h = max(3.0, canvas.shape[0] / 50)
    fig = plt.figure(figsize=(fig_w, fig_h), dpi=100)
    plt.imshow(canvas, interpolation="nearest")
    if args.labels:
        for k, idx in enumerate(indices):
            r, c = divmod(k, cols)
            plt.text(c * cw + cw / 2, r * ch + ch - 1, str(idx), ha="center", va="bottom",
                     fontsize=5, color="#303030")
    plt.axis("off")
    plt.title(f"PurrGO icons {w}x{h}, shown {len(indices)} of {n}"
              f" (scale {args.scale}x)", pad=12, fontsize=11, fontweight="bold")
    plt.tight_layout()
    fig.savefig(args.output, bbox_inches="tight", facecolor="#D9D9D9")
    print(f"Готово: показано {len(indices)} из {n} иконок {w}x{h}, файл '{args.output}'.")
    if not args.no_show:
        plt.show()


if __name__ == "__main__":
    main()
